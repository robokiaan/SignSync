// Load Lessons in Dashboard
async function loadLessons() {
    try {
        // Difficulty loads alongside the lessons so each sign button can carry
        // its own pose count - the lesson-level tag below is category-derived
        // and says nothing about how hard the individual signs in it are.
        await Promise.all([loadSiteData(), loadDifficulty()]);
        // siteData.lessons already arrives in the intended display order
        // (scripts/build_static_data.py's CATEGORY_RELEVANCE_ORDER) - no
        // client-side re-sort. A difficulty-tier sort used to run here, but
        // that fought the relevance order (e.g. bumped beginner-tier
        // Colours ahead of intermediate-tier People despite People ranking
        // higher for relevance).
        const lessons = siteData.lessons;

        const container = document.getElementById("dashboard-lessons-container");
        container.innerHTML = "";

        lessons.forEach((lesson) => {
            const lessonCard = document.createElement("div");
            lessonCard.className = "lesson-card glass";

            // Within a lesson, signs run easiest to hardest so a learner works
            // up through a category instead of hitting a 5-pose sign first
            // because its name starts with A. Alphabetical is the tiebreak
            // inside a tier, and a sign with no phase model sorts last rather
            // than being treated as 0 poses. slice() because siteData.lessons
            // is the cached copy every later render reads from.
            const items = lesson.items.slice().sort((a, b) => {
                const ra = difficultyFor(a.sign.sign_name)?.holds ?? Infinity;
                const rb = difficultyFor(b.sign.sign_name)?.holds ?? Infinity;
                if (ra !== rb) return ra - rb;
                return a.sign.sign_name.localeCompare(b.sign.sign_name);
            });

            let itemsListHtml = '<div style="display:flex; flex-wrap:wrap; gap: 0.5rem; margin-top: 0.75rem;">';
            items.forEach((item) => {
                // Same pose-count difficulty the dictionary shows, condensed to
                // fit a button: a coloured left edge plus the pose count. The
                // full wording lives in the tooltip.
                const diff = difficultyFor(item.sign.sign_name);
                const pip = diff
                    ? `<span class="pose-pip">${diff.holds}</span>`
                    : "";
                const title = diff
                    ? `${diff.label} - ${diff.holds} pose${diff.holds > 1 ? "s" : ""} to match`
                    : "Difficulty unknown";
                itemsListHtml += `
                    <button class="btn btn-secondary sign-chip${diff ? ` diff-${diff.key}` : ""}" title="${title}" onclick="startPractice('${item.sign.sign_name}', '${lesson.title}')" style="width:auto; padding:0.4rem 0.8rem; font-size:0.85rem; text-transform:capitalize;">
                        🎬 ${item.sign.sign_name}${pip}
                    </button>
                `;
            });
            itemsListHtml += "</div>";

            lessonCard.innerHTML = `
                <div class="lesson-details">
                    <div class="tag-list">
                        <span class="tag tag-beginner">${lesson.difficulty_level}</span>
                        <span class="tag tag-category">${lesson.category}</span>
                    </div>
                    <h3 style="margin-top: 0.5rem;">${lesson.title}</h3>
                    <p>${lesson.description || "No description provided."}</p>
                    ${itemsListHtml}
                </div>
            `;
            container.appendChild(lessonCard);
        });
    } catch (err) {
        console.error("Error loading lessons:", err);
    }
}

// Load Dictionary Grid
async function loadDictionary() {
    const category = document.getElementById("dict-category-select").value;

    try {
        await Promise.all([loadSiteData(), loadDifficulty()]);
        const filtered = category
            ? siteData.dictionary.filter((s) => s.category === category)
            : siteData.dictionary;
        const container = document.getElementById("dictionary-container");
        container.innerHTML = "";

        if (filtered.length === 0) {
            container.innerHTML = `<p style="grid-column: 1/-1; text-align:center; color:var(--text-secondary); margin-top:2rem;">No signs found in this category.</p>`;
            return;
        }

        // Easiest first by default, matching the dashboard: a learner browsing
        // the dictionary should meet one-pose signs before five-pose ones.
        // Alphabetical is the tiebreak within a tier, and stays available as an
        // explicit "A to Z" choice for looking up a word you already know.
        const sortEl = document.getElementById("dict-sort-select");
        const sortBy = sortEl ? sortEl.value : "easiest";
        const signs = filtered.slice();
        if (sortBy === "easiest" || sortBy === "hardest") {
            const rank = (s) => {
                const d = difficultyFor(s.sign_name);
                return d ? d.holds : Infinity; // unknown difficulty sorts last either way
            };
            const dir = sortBy === "easiest" ? 1 : -1;
            signs.sort((a, b) => {
                const ra = rank(a), rb = rank(b);
                if (ra !== rb) {
                    if (ra === Infinity) return 1;
                    if (rb === Infinity) return -1;
                    return (ra - rb) * dir;
                }
                return a.sign_name.localeCompare(b.sign_name);
            });
        }

        signs.forEach((sign) => {
            const dictCard = document.createElement("div");
            const diff = difficultyFor(sign.sign_name);
            dictCard.className = "dict-card glass" + (diff ? ` diff-${diff.key}` : "");
            dictCard.onclick = () => startPractice(sign.sign_name, "Dictionary Search");
            const poses = diff ? `${diff.holds} pose${diff.holds > 1 ? "s" : ""}` : "";
            const diffTag = diff
                ? `<span class="tag tag-${diff.key}" title="${poses} to match">${diff.label} · ${poses}</span>`
                : "";
            dictCard.innerHTML = `
                <h3>${sign.sign_name}</h3>
                <div class="tag-list">
                    <span class="tag tag-category">${sign.category}</span>
                    ${diffTag}
                </div>
                <p>${sign.description || "Practice standard signs mapped directly from the INCLUDE dataset."}</p>
            `;
            container.appendChild(dictCard);
        });
    } catch (err) {
        console.error("Error loading dictionary:", err);
    }
}

// Load Sentences List
async function loadSentences() {
    try {
        await loadSiteData();
        const sentences = [...siteData.sentences];

        const difficultyOrder = { beginner: 1, intermediate: 2, advanced: 3 };
        sentences.sort((a, b) => {
            const diffA = difficultyOrder[a.difficulty_level.toLowerCase()] || 99;
            const diffB = difficultyOrder[b.difficulty_level.toLowerCase()] || 99;
            return diffA - diffB;
        });

        const container = document.getElementById("sentences-list-container");
        container.innerHTML = "";

        if (sentences.length === 0) {
            container.innerHTML = `<p style="color:var(--text-secondary);">No sentences available yet.</p>`;
            return;
        }

        sentences.forEach((sentence) => {
            const card = document.createElement("div");
            card.className = "lesson-card glass";
            const glossPreview = sentence.items.map((item) => item.sign.sign_name).join(" · ");
            card.innerHTML = `
                <div class="lesson-details" style="width:100%;">
                    <div class="tag-list">
                        <span class="tag tag-beginner">${sentence.difficulty_level}</span>
                        <span class="tag tag-category">${sentence.items.length} sign${sentence.items.length === 1 ? "" : "s"}</span>
                    </div>
                    <h3 style="margin-top: 0.5rem;">${sentence.english_text}</h3>
                    <p style="text-transform:capitalize;">${glossPreview}</p>
                    <button class="btn btn-primary" style="width:auto; margin-top:0.75rem; padding:0.5rem 1.25rem;" onclick="startSentencePractice(${sentence.id})">
                        ▶ Practice
                    </button>
                </div>
            `;
            container.appendChild(card);
        });
    } catch (err) {
        console.error("Error loading sentences:", err);
    }
}

// Enter the practice arena in sentence mode. Shared by the curated-list flow
// (startSentencePractice/startSentencePracticeBySlug) and the write-your-own
// flow (practiceCustomSentence) - all already know the gloss word list, so
// none needs anything beyond this DOM/session setup. `slug` is only present
// for curated sentences, so it's what makes the URL deep-linkable; a typed
// sentence doesn't get a URL of its own.
function enterSentenceArena(englishText, glossWords, slug) {
    activeSign = null;
    document.getElementById("btn-arena-back").onclick = () => switchPage("sentences");

    document.getElementById("practice-lesson-title").textContent = "SENTENCE PRACTICE";
    document.getElementById("practice-sign-name").textContent = englishText;
    document.getElementById("practice-sign-desc").textContent = `Sign ${glossWords.length} word${glossWords.length === 1 ? "" : "s"} in order.`;

    switchPage("practice");
    if (slug) setUrl(`/sentences/${encodeURIComponent(slug)}`);

    // Reset button is single-sign-practice only - sentence mode redoes
    // automatically when you go back to the first word (resumeCombinedModel).
    document.getElementById("btn-reset-attempt").style.display = "none";

    // Reference video defaults to shown. Set explicitly rather than relying
    // on whatever opacity single-sign practice's own toggle last left behind -
    // coach.js's video-chain loading (playCombinedVideo/loadChainedWord)
    // never touches opacity itself, only display:block/none.
    const showSignToggle = document.getElementById("toggle-disable-video");
    handleVideoToggle(showSignToggle ? showSignToggle.checked : true);

    resetDTWSequences();
    resetCoachState();
    startWebcamStream();

    beginSentenceSession(englishText, glossWords);
}

// Start a sentence practice session from the curated list. All words' phase
// models are already precomputed (phases.json, fetched up front by coach.js),
// so this needs no live per-word priming. Returns true/false so callers
// (incl. the URL router) know whether to fall back to the sentences list.
async function startSentencePractice(sentenceId) {
    try {
        await loadSiteData();
        const sentence = siteData.sentences.find((s) => s.id === sentenceId);
        if (!sentence) {
            showAlert("Error loading sentence.", "error");
            return false;
        }
        const glossWords = sentence.items.map((item) => item.sign.sign_name.toLowerCase());
        enterSentenceArena(sentence.english_text, glossWords, sentence.slug);
        return true;
    } catch (err) {
        console.error("Error starting sentence practice:", err);
        showAlert("Could not start sentence practice.", "error");
        return false;
    }
}

// Same as startSentencePractice, but resolved by URL slug instead of id -
// what deep-linking to /sentences/<slug> uses.
async function startSentencePracticeBySlug(slug) {
    try {
        await loadSiteData();
        const sentence = siteData.sentences.find((s) => s.slug === slug);
        if (!sentence) {
            showAlert("Error loading sentence.", "error");
            return false;
        }
        const glossWords = sentence.items.map((item) => item.sign.sign_name.toLowerCase());
        enterSentenceArena(sentence.english_text, glossWords, sentence.slug);
        return true;
    } catch (err) {
        console.error("Error starting sentence practice:", err);
        showAlert("Could not start sentence practice.", "error");
        return false;
    }
}

// Inline warning under the write-your-own input. Persistent (unlike showAlert's
// 4s toast) so the learner can read which words to change, and cleared as soon
// as they edit the sentence.
function showCustomSentenceWarning(message) {
    const el = document.getElementById("custom-sentence-warning");
    if (!el) return;
    el.textContent = message;
    el.style.display = "block";
}

function clearCustomSentenceWarning() {
    const el = document.getElementById("custom-sentence-warning");
    if (el) el.style.display = "none";
}

// "Practice" button for a sentence the learner wrote. The sentence is first
// turned into its ISL gloss by rule (toGloss: function words dropped, NOT and
// question words last, time / nouns / adjective / verb order), and THEN every
// gloss sign is checked against the dictionary. If any is missing, practice is
// refused and the learner is shown the gloss with the missing signs named -
// "I don't have food" becomes I FOOD HAVE NOT, and I, FOOD, HAVE and NOT are
// all reported - because the coach has no reference to grade them against.
async function practiceCustomSentence() {
    const input = document.getElementById("custom-sentence-input");
    const text = (input.value || "").trim();
    clearCustomSentenceWarning();
    if (!text) {
        showCustomSentenceWarning("Write a sentence first.");
        return;
    }
    try {
        await loadSiteData();
        const { gloss: tokens, missing } = toGloss(text, aliasIndex, categoryByName);
        const glossText = tokens.map((t) => t.label.toUpperCase()).join(" ");
        if (missing.length > 0) {
            const quoted = missing.map((w) => w.toUpperCase());
            const list = quoted.length === 1
                ? quoted[0]
                : `${quoted.slice(0, -1).join(", ")} and ${quoted[quoted.length - 1]}`;
            showCustomSentenceWarning(
                `In ISL this is signed "${glossText}", but ${list} ${quoted.length === 1 ? "is" : "are"} ` +
                "not available in this dictionary. Change or remove the word, or pick words from the Dictionary tab."
            );
            return;
        }
        if (tokens.length === 0) {
            showCustomSentenceWarning("No signable words found - add a word from the Dictionary tab.");
            return;
        }
        const gloss = tokens.map((t) => t.sign);
        showAlert(`ISL order: ${glossText}`);
        enterSentenceArena(text, gloss);
    } catch (err) {
        console.error("Error parsing custom sentence:", err);
        showCustomSentenceWarning("Could not start practice for that sentence.");
    }
}

// Start Practice Session. Returns true/false so callers (incl. the URL
// router) know whether to fall back to a list page.
async function startPractice(signName, lessonTitle) {
    try {
        await loadSiteData();
        const sign = dictionaryByName.get(signName.toLowerCase());
        if (!sign) {
            showAlert("Error loading sign.", "error");
            return false;
        }
        activeSign = sign;
        endSentenceSession();
        document.getElementById("btn-arena-back").onclick = () => switchPage("dashboard");

        document.getElementById("practice-lesson-title").textContent = lessonTitle;
        document.getElementById("practice-sign-name").textContent = activeSign.sign_name;
        document.getElementById("practice-sign-desc").textContent = activeSign.description || "N/A";

        switchPage("practice");

        const signKey = activeSign.sign_name.toLowerCase();

        // Manual reset is only useful for single-hold signs: a multi-hold sign
        // already auto-detects returning to hold 1 and restarts itself (see
        // coach.js's "Attempt restart" logic), so the button would be a
        // redundant, easy-to-mispress no-op there. precomputedPhasesPromise
        // (from coach.js) resolves near-instantly since phases.json is fetched
        // once at page load, well before any sign gets clicked.
        const precomputedPhases = await precomputedPhasesPromise;
        const holdCount = precomputedPhases[signKey]?.holds?.length ?? 0;
        document.getElementById("btn-reset-attempt").style.display = holdCount > 1 ? "none" : "";

        // Reset coach + DTW buffers before priming the new reference.
        resetDTWSequences();
        resetCoachState();
        startWebcamStream();

        setUrl(`/dashboard/${encodeURIComponent(signKey)}`);

        const video = document.getElementById("practice-ref-video");
        const placeholder = document.getElementById("video-placeholder");
        if (video && placeholder) {
            video.pause();
            video.style.display = "none";
            placeholder.style.display = "block";
            document.getElementById("video-placeholder-text").innerHTML = `Loading reference video for <strong>${activeSign.sign_name}</strong>...`;

            video.onerror = () => {
                console.error("Reference video failed to load:", {
                    sign: activeSign.sign_name,
                    code: video.error ? video.error.code : null,
                    message: video.error ? video.error.message : "unknown",
                    src: video.src,
                });

                placeholder.style.display = "block";
                document.getElementById("video-placeholder-text").innerHTML = `
                    <div style="font-size: 2.5rem; margin-bottom: 0.5rem;">📹</div>
                    Reference video not found at:<br>
                    <code style="color:#f43f5e; background:rgba(0,0,0,0.3); padding:0.2rem 0.5rem; border-radius:4px; font-size:0.8rem; display:inline-block; margin-top:0.5rem;">app/static/videos/${activeSign.sign_name.toLowerCase()}.mp4</code>
                `;
                video.style.display = "none";
            };

            video.onloadeddata = () => {
                placeholder.style.display = "none";
                video.style.display = "block";

                // Prime the DTW reference (runs the video through the single
                // MediaPipe model once, then caches it). After priming, loop the
                // video muted for the learner to follow along.
                refReadyPromise = primeReference(signKey).then(() => {
                    const toggle = document.getElementById("toggle-disable-video");
                    handleVideoToggle(toggle ? toggle.checked : false);
                    video.playbackRate = parseFloat(document.getElementById("video-speed-select").value || "1");
                    video.loop = true;
                    video.play().catch(() => {});
                });
            };

            // No crossOrigin here on purpose: every sign in the dictionary has a
            // precomputed phase model (phases.json), so primeReference() never
            // reads frames off a canvas anymore - and setting crossOrigin on a
            // cross-origin host that doesn't send CORS headers (e.g. GitHub
            // Releases) would make the browser refuse to even play the video.
            video.src = videoUrl(signKey);
            video.load();
        }
        return true;
    } catch (err) {
        console.error("Error starting practice:", err);
        showAlert("Could not start practice session.", "error");
        return false;
    }
}

function stopPracticeArena() {
    stopWebcamStream();

    const video = document.getElementById("practice-ref-video");
    if (video) {
        video.pause();
        video.onloadeddata = null;
        video.onerror = null;
        video.src = "";
        video.style.display = "none";
    }
    resetDTWSequences();
    endSentenceSession();

    // Reference video defaults to shown - leave the checkbox checked so
    // re-entering practice (a different sign, or coming back later) keeps
    // showing it by default, not just on the very first page load.
    const toggle = document.getElementById("toggle-disable-video");
    if (toggle) toggle.checked = true;
    handleVideoToggle(false);

    document.getElementById("btn-reset-attempt").style.display = "none";

    const placeholder = document.getElementById("video-placeholder");
    if (placeholder) {
        placeholder.style.display = "block";
        document.getElementById("video-placeholder-text").innerHTML = `Please select a sign to start practicing.`;
    }
}

function toggleVideoPlay() {
    const video = document.getElementById("practice-ref-video");
    if (!video) return;
    if (video.paused) video.play();
    else video.pause();
}

function changeVideoSpeed(speed) {
    const video = document.getElementById("practice-ref-video");
    if (!video) return;
    video.playbackRate = parseFloat(speed);
}

function handleVideoToggle(isShowSign) {
    const target = document.getElementById("practice-ref-video");
    if (!target) return;
    if (isShowSign) {
        target.style.opacity = "1";
        target.style.pointerEvents = "auto";

        // The video keeps looping in the background while hidden, so by the
        // time "Show Sign" is checked it can be mid-motion. Rewind to the
        // dormant/rest frame at the start of the clip and resume from there
        // so revealing it always looks like a clean start, not a jump-cut.
        target.pause();
        const resume = () => {
            target.removeEventListener("seeked", resume);
            target.play().catch(() => {});
        };
        target.addEventListener("seeked", resume);
        target.currentTime = 0;
    } else {
        target.style.opacity = "0";
        target.style.pointerEvents = "none";
    }
}
