// Where the reference .mp4 files are served from. The 1.3 GB video set is not
// in the repo (gitignored) - it lives as assets on a GitHub Release, which is
// what the deployed site streams from. On localhost the same clips are read
// from app/static/videos under their original names instead, so local dev and
// the phase-labelling scripts keep working offline. No CORS is needed either
// way: nothing reads video pixels back off a canvas any more.
//
// Release assets can't carry spaces or brackets, so each clip is stored under
// a slug (videoAssetName): "you (plural)" -> you_plural.mp4. Regenerate with
// the same rule if the set is ever re-uploaded.
const VIDEO_RELEASE_URL = "https://github.com/robokiaan/SignSync/releases/download/videos-v1";
const VIDEO_LOCAL_URL = "videos";
const USE_LOCAL_VIDEOS = location.hostname === "localhost" || location.hostname === "127.0.0.1";

function videoAssetName(signName) {
    return signName.toLowerCase().replace(/[^a-z0-9]+/g, "_").replace(/^_+|_+$/g, "") + ".mp4";
}

function videoUrl(signName) {
    if (USE_LOCAL_VIDEOS) return `${VIDEO_LOCAL_URL}/${encodeURIComponent(signName)}.mp4`;
    return `${VIDEO_RELEASE_URL}/${videoAssetName(signName)}`;
}

// Site content (dictionary/lessons/sentences) baked to static JSON by
// scripts/build_static_data.py - there's no backend on GitHub Pages to serve
// /api/* at request time, so this loads once and everything below reads from
// it in memory instead of fetching per page. dictionaryByName backs sign
// lookup the same way the old /api/dictionary/{name} endpoint did server-side;
// aliasIndex + categoryByName (gloss_matching.js) back the typed-sentence flow.
let siteData = null;
let dictionaryByName = new Map();
let aliasIndex = new Map();
let categoryByName = new Map();
let siteDataPromise = null;

function loadSiteData() {
    if (!siteDataPromise) {
        // no-cache: these files get regenerated by scripts/build_static_data.py
        // on every deploy, with no cache-busting query string of their own -
        // without this, browsers cache them past a rebuild the same way
        // index.html/app.js did before that got fixed.
        const opts = { cache: "no-cache" };
        siteDataPromise = Promise.all([
            fetch("data/dictionary.json", opts).then((r) => r.json()),
            fetch("data/lessons.json", opts).then((r) => r.json()),
            fetch("data/sentences.json", opts).then((r) => r.json()),
        ]).then(([dictionary, lessons, sentences]) => {
            siteData = { dictionary, lessons, sentences };
            dictionaryByName = new Map(dictionary.map((s) => [s.sign_name, s]));
            aliasIndex = buildAliasIndex(dictionary.map((s) => s.sign_name));
            categoryByName = new Map(dictionary.map((s) => [s.sign_name, s.category]));
        });
    }
    return siteDataPromise;
}

// A sign's difficulty is how many held poses it has: a 1-pose sign is a single
// shape to hit, while a 5-pose sign is a whole ordered sequence, each pose
// scored separately. Hold counts come from phases.json (the same file the coach
// scores against), so difficulty can never drift out of sync with what the
// learner is actually graded on. Cached like siteData - the browser already has
// this file from the practice page.
let holdCountByName = new Map();
let difficultyPromise = null;

const DIFFICULTY_TIERS = [
    { max: 1, key: "easy", label: "Easy" },
    { max: 2, key: "medium", label: "Medium" },
    { max: 3, key: "hard", label: "Hard" },
    { max: Infinity, key: "expert", label: "Expert" },
];

function loadDifficulty() {
    if (!difficultyPromise) {
        difficultyPromise = fetch("phases.json", { cache: "no-cache" })
            .then((r) => r.json())
            .then((phases) => {
                holdCountByName = new Map(
                    Object.entries(phases).map(([name, model]) => [name, (model.holds || []).length])
                );
            })
            .catch((err) => {
                // Difficulty is decoration - a failed fetch hides the badges
                // rather than taking the whole dictionary page down with it.
                console.error("Could not load sign difficulty:", err);
                holdCountByName = new Map();
            });
    }
    return difficultyPromise;
}

// null for a sign with no phase model yet, so callers can omit the badge
// instead of labelling an unknown sign "Easy".
function difficultyFor(signName) {
    const holds = holdCountByName.get(signName);
    if (!holds) return null;
    const tier = DIFFICULTY_TIERS.find((t) => holds <= t.max);
    return { ...tier, holds };
}

// URL routing: deep-linkable /dashboard/<sign> and /sentences/<slug>, plus
// plain /dashboard, /dictionary, /sentences for the list pages. The "practice"
// page itself has no route of its own - whichever sign/sentence started the
// session owns the URL, set by startPractice/enterSentenceArena below.
//
// suppressUrlUpdate guards against feedback loops: handleRoute (run on load
// and on popstate, i.e. the URL already changed) drives the same
// switchPage/startPractice/enterSentenceArena calls that normal in-app clicks
// use, and those calls call setUrl - which must be a no-op in that direction.
let suppressUrlUpdate = false;

// Mount point of the app on this host ("" at an origin root, "/<repo>" on a
// GitHub Pages project site) - set by the inline script in index.html that
// also inserts the matching <base>. Routes are written and read relative to
// it, so /SignSync/dashboard/hello and /dashboard/hello are the same route.
function appBase() {
    return window.APP_BASE || "";
}

function appPath(pathname) {
    const base = appBase();
    if (base && pathname.startsWith(base)) return pathname.slice(base.length) || "/";
    return pathname;
}

function setUrl(path) {
    if (suppressUrlUpdate) return;
    const full = appBase() + path;
    if (location.pathname !== full) history.pushState({}, "", full);
}

async function handleRoute(path) {
    suppressUrlUpdate = true;
    try {
        await loadSiteData();
        const parts = path.split("/").filter(Boolean);
        if (parts[0] === "dashboard" && parts[1]) {
            const ok = await startPractice(decodeURIComponent(parts[1]), "Dashboard");
            if (!ok) switchPage("dashboard");
        } else if (parts[0] === "sentences" && parts[1]) {
            const ok = await startSentencePracticeBySlug(decodeURIComponent(parts[1]));
            if (!ok) switchPage("sentences");
        } else if (parts[0] === "dictionary") {
            switchPage("dictionary");
        } else if (parts[0] === "sentences") {
            switchPage("sentences");
        } else {
            switchPage("dashboard");
        }
    } finally {
        suppressUrlUpdate = false;
    }
}

window.addEventListener("popstate", () => handleRoute(appPath(location.pathname)));

// Initialize App -> route off the current URL (no authentication).
document.addEventListener("DOMContentLoaded", () => {
    handleRoute(appPath(location.pathname));
});

// Navigation Router
function switchPage(pageId) {
    const pages = ["dashboard", "dictionary", "practice", "sentences"];
    if (!pages.includes(pageId)) pageId = "dashboard";

    pages.forEach((p) => {
        document.getElementById(`page-${p}`).classList.remove("active");
    });

    ["nav-dashboard", "nav-dictionary", "nav-sentences"].forEach((btnId) => {
        const btn = document.getElementById(btnId);
        if (btn) btn.classList.remove("active");
    });

    document.getElementById(`page-${pageId}`).classList.add("active");
    activePage = pageId;

    document.getElementById("main-header").style.display = "flex";
    if (pageId === "dashboard") document.getElementById("nav-dashboard").classList.add("active");
    if (pageId === "dictionary") document.getElementById("nav-dictionary").classList.add("active");
    if (pageId === "sentences") document.getElementById("nav-sentences").classList.add("active");

    // Load data specific to the page
    if (pageId === "dashboard") {
        loadLessons();
    } else if (pageId === "dictionary") {
        loadDictionary();
    } else if (pageId === "sentences") {
        loadSentences();
    }

    // Terminate webcam/reference when leaving the practice arena
    if (pageId !== "practice") {
        stopPracticeArena();
    }

    // "practice" has no route of its own - the sign/sentence that started it
    // owns the URL (set separately by startPractice/enterSentenceArena).
    if (pageId !== "practice") {
        setUrl(`/${pageId}`);
    }
}

